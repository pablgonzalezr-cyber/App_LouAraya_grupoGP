CREATE SEQUENCE IF NOT EXISTS producto_ids START WITH 9 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    material VARCHAR(100) NOT NULL,
    ancho_cm NUMERIC(7,2) NOT NULL,
    alto_cm NUMERIC(7,2) NOT NULL,
    precio NUMERIC(11,2) NOT NULL,
    disponible BOOLEAN NOT NULL,
    publicado BOOLEAN NOT NULL,
    archivado BOOLEAN DEFAULT FALSE NOT NULL
);

-- Compatibilidad con archivos H2 anteriores a la eliminación lógica.
ALTER TABLE productos ADD COLUMN IF NOT EXISTS archivado BOOLEAN DEFAULT FALSE NOT NULL;

CREATE TABLE IF NOT EXISTS colecciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    activa BOOLEAN NOT NULL,
    publicada BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS coleccion_productos (
    coleccion_id BIGINT NOT NULL REFERENCES colecciones(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    PRIMARY KEY (coleccion_id, producto_id)
);
CREATE INDEX IF NOT EXISTS idx_coleccion_producto ON coleccion_productos(producto_id);

CREATE TABLE IF NOT EXISTS campanias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    inicio DATE NOT NULL,
    termino DATE NOT NULL,
    publicada BOOLEAN NOT NULL,
    activa BOOLEAN NOT NULL
);
