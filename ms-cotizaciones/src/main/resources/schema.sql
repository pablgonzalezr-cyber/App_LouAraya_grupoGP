CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(254) NOT NULL,
    clave_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_clientes_correo UNIQUE (correo)
);

CREATE TABLE IF NOT EXISTS cotizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    token_envio VARCHAR(36) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    material VARCHAR(100) NOT NULL,
    ancho_cm NUMERIC(16,6) NOT NULL,
    largo_cm NUMERIC(16,6) NOT NULL,
    cantidad INTEGER NOT NULL,
    fecha_requerida DATE,
    producto_referencia_id BIGINT,
    producto_referencia_nombre VARCHAR(150),
    creada_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    estado ENUM('APROBADA', 'EN_REVISION', 'PENDIENTE', 'RECHAZADA') NOT NULL,
    CONSTRAINT uk_cotizacion_cliente_token UNIQUE (cliente_id, token_envio)
);
